#!/usr/bin/env python3
"""
4MLSim build script (run from the repository root):

    python3 tools/build.py

1. Writes sw.js: the offline helper with the full list of app files, so every
   module works offline after the first visit (cache name changes with content).
2. Writes 4MLSim-offline.html: a single self-contained file with every page,
   style, script, font and image inlined, for computers with no internet.

No third-party Python packages are needed.
"""
import base64, hashlib, json, mimetypes, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

def read(p, mode='r'):
    with open(p, mode, **({} if 'b' in mode else {'encoding': 'utf-8'})) as f:
        return f.read()

def write(p, s):
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(s)

def version():
    m = re.search(r"version:\s*'([^']+)'", read('assets/js/core.js'))
    return m.group(1) if m else '0.0.0'

PAGES = ['index.html', 'about.html'] + sorted('modules/' + f for f in os.listdir('modules') if f.endswith('.html'))
SKIP = {'sw.js', '4MLSim-offline.html'}

def app_files():
    out = ['./', 'index.html', 'about.html', 'manifest.json']
    for base in ('modules', 'assets'):
        for dp, dn, fn in os.walk(base):
            dn.sort()
            for f in sorted(fn):
                if f.startswith('LICENSE') or f.endswith('.map'):
                    continue
                out.append(os.path.join(dp, f).replace(os.sep, '/'))
    return [p for p in dict.fromkeys(out) if p not in SKIP]

# ---------------------------------------------------------------- sw.js
def build_sw():
    files = app_files()
    h = hashlib.sha1()
    for f in files:
        if f != './':
            h.update(f.encode()); h.update(read(f, 'rb'))
    cache = '4mlsim-v' + version() + '-' + h.hexdigest()[:10]
    sw = """/* 4MLSim offline helper (generated by tools/build.py; do not edit by hand).
   App files: try the internet first so a new version on GitHub is picked up at once,
   fall back to the saved copy when offline. Every file is saved at install time,
   so all modules work offline after the first visit. */
const CACHE = '%s';
const FILES = %s;

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('4mlsim-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  e.respondWith(
    fetch(req, { cache: 'no-cache' }).then(res => {
      if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match(req, { ignoreSearch: true }).then(r => r || (req.mode === 'navigate' ? caches.match('./index.html') : undefined)))
  );
});
""" % (cache, json.dumps(files, indent=2))
    write('sw.js', sw)
    print('sw.js: %d files, cache %s' % (len(files), cache))

# ---------------------------------------------------------------- bundle
def data_uri(path):
    mime = mimetypes.guess_type(path)[0] or 'application/octet-stream'
    if path.endswith('.woff2'): mime = 'font/woff2'
    if path.endswith('.svg'): mime = 'image/svg+xml'
    return 'data:%s;base64,%s' % (mime, base64.b64encode(read(path, 'rb')).decode())

def inline_css(path):
    css = read(path)
    d = os.path.dirname(path)
    def rep(m):
        ref = m.group(1).strip('\'"')
        if ref.startswith('data:') or ref.startswith('http'):
            return m.group(0)
        return 'url(' + data_uri(os.path.normpath(os.path.join(d, ref))) + ')'
    return re.sub(r'url\(([^)]+)\)', rep, css)

def norm(page, ref):
    return os.path.normpath(os.path.join(os.path.dirname(page), ref)).replace(os.sep, '/')

def build_bundle():
    assets = {}       # shared css/js, inlined once
    pages = {}
    for page in PAGES:
        html = read(page)
        html = re.sub(r'\s*<link rel="(manifest|icon|apple-touch-icon)"[^>]*>', '', html)
        def css_rep(m):
            p = norm(page, m.group(1))
            if p not in assets: assets[p] = inline_css(p)
            return '<style data-asset="%s"></style>' % p
        html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', css_rep, html)
        def js_rep(m):
            p = norm(page, m.group(1))
            if p not in assets: assets[p] = read(p)
            return '<script data-asset="%s"></script>' % p
        html = re.sub(r'<script src="([^"]+)"></script>', js_rep, html)
        pages[page] = html
    images = {p: data_uri(p) for p in ('assets/img/icon.svg', 'assets/img/emef-lab-logo.png')}
    lazy = {'assets/vendor/xlsx.core.min.js': read('assets/vendor/xlsx.core.min.js')}

    def js_str(s):
        # safe inside a <script> element
        return json.dumps(s).replace('</', '<\\/').replace('<!--', '<\\u0021--')

    shell = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>4MLSim b%(buildno)s (offline)</title>
<link rel="icon" href="%(icon)s">
<style>html,body{margin:0;height:100%%;background:#F7F5F0}iframe{border:0;width:100%%;height:100%%;display:block}</style>
</head>
<body>
<iframe id="app" title="4MLSim"></iframe>
<script>
/* 4MLSim v%(ver)s, single-file offline version (generated by tools/build.py).
   (c) 2026 Periklis Gogas, EMEF Lab. MIT License. Third-party parts: Temml (MIT),
   SheetJS CE (Apache-2.0), IBM Plex, Fraunces, STIX Two Math fonts (SIL OFL). */
const ASSETS = %(assets)s;
const PAGES = %(pages)s;
const IMAGES = %(images)s;
const LAZY = %(lazy)s;
const frame = document.getElementById('app');
function esc(s) { return s.replace(/<\\/script/gi, '<\\\\/script'); }
function compose(path) {
  let html = PAGES[path];
  html = html.replace(/<style data-asset="([^"]+)"><\\/style>/g, (m, p) => '<style>' + ASSETS[p] + '</style>');
  html = html.replace(/<script data-asset="([^"]+)"><\\/script>/g, (m, p) => '<script>' + esc(ASSETS[p]) + '<\\/script>');
  const boot = '<script>window.MLS_IN_BUNDLE=true;window.MLS_BASE="";window.MLS_BUNDLE_ASSETS=' + JSON.stringify(IMAGES) +
    ';window.MLS_BUNDLE_SCRIPTS=' + esc(JSON.stringify(LAZY)) + ';<\\/script>';
  return html.replace('<head>', () => '<head>' + boot);
}
function go(path, push) {
  path = (path || 'index.html').replace(/^\\.?\\//, '').split('#')[0];
  if (!PAGES[path]) return;
  frame.srcdoc = compose(path);
  if (push !== false) { try { history.pushState(null, '', '#/' + path); } catch (e) { /* sandboxed preview */ } }
  document.title = '4MLSim b%(buildno)s (offline)';
}
window.addEventListener('message', e => { if (e.data && e.data.mls === 'nav') go(e.data.href); });
window.addEventListener('popstate', () => go(location.hash.slice(2), false));
go(location.hash.slice(2) || 'index.html', false);
</script>
</body>
</html>
""" % {'icon': images['assets/img/icon.svg'], 'ver': version(), 'buildno': re.search(r"buildNo:\s*(\d+)", read('assets/js/core.js')).group(1), 'assets': js_str(assets),
        'pages': js_str(pages), 'images': json.dumps(images), 'lazy': js_str(lazy)}
    write('4MLSim-offline.html', shell)
    print('4MLSim-offline.html: %d pages, %.1f MB' % (len(pages), os.path.getsize('4MLSim-offline.html') / 1e6))

if __name__ == '__main__':
    build_sw()
    build_bundle()
